"""Two example helpers for px4.yaml. A sketch to read, not the team's verifier.

    pip install pyulog
    python helpers_example.py flight.ulg 50 0 20 5

The four numbers are the waypoint's x, y, z and the visit distance, all in metres.
The visit distance has no default because the team has not chosen one.
Generated by Claude, I did not check this yet! Probably works though...
"""

import sys
from math import dist

from pyulog import ULog

TOPIC = "vehicle_local_position_groundtruth"


def path_flown(log_path):
    """Return [(seconds, north, east, up), ...] in metres from where the drone started.

    This is the agent.x, agent.y and agent.z mapping in px4.yaml:
    subtract the first logged value, and flip z because PX4's z points down.
    """
    data = ULog(log_path, [TOPIC]).get_dataset(TOPIC).data
    x0, y0, z0 = data["x"][0], data["y"][0], data["z"][0]
    return [
        (t / 1e6, x - x0, y - y0, -(z - z0))
        for t, x, y, z in zip(
            data["timestamp"], data["x"], data["y"], data["z"], strict=True
        )
    ]


def visited(path, waypoint, distance_m):
    """True if any recorded position is within distance_m of the waypoint (x, y, z).

    This is the waypoint.visited mapping in px4.yaml. Distance is straight-line (3D).
    """
    return any(
        dist((north, east, up), waypoint) <= distance_m for _, north, east, up in path
    )


if __name__ == "__main__":
    log_path, wx, wy, wz, distance_m = sys.argv[1], *map(float, sys.argv[2:6])
    path = path_flown(log_path)
    _, north, east, up = path[-1]
    print(f"final position: x={north:.2f} y={east:.2f} z={up:.2f}")
    print(f"visited within {distance_m} m: {visited(path, (wx, wy, wz), distance_m)}")
